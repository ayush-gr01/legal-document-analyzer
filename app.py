import streamlit as st
import os
from pathlib import Path

from src.rag_pipeline import RAGPipeline

st.set_page_config(page_title="AI Legal Document Analyzer", layout="wide")

st.title("AI Legal Document Analyzer")
st.caption("Upload legal PDFs, ask questions, and extract key clauses. \n*This tool provides information only and is not legal advice.*")

# Sidebar for uploads and settings
with st.sidebar:
    st.header("Upload Documents")
    uploaded_files = st.file_uploader("Upload PDF files", type=["pdf"], accept_multiple_files=True)
    if st.button("Clear All Documents"):
        if "pipeline" in st.session_state:
            st.session_state.pipeline.clear()
            del st.session_state.pipeline
        st.success("Session cleared.")
    st.header("Settings")
    chunk_size = st.slider("Chunk size (characters)", min_value=500, max_value=2000, value=1000, step=100)
    chunk_overlap = st.slider("Chunk overlap", min_value=0, max_value=500, value=200, step=50)
    top_k = st.slider("Number of retrieved passages", min_value=1, max_value=10, value=4)
    if st.button("Apply Settings"):
        # Reinitialize pipeline with new settings
        if "pipeline" in st.session_state:
            st.session_state.pipeline.__init__(chunk_size=chunk_size, chunk_overlap=chunk_overlap, top_k=top_k)
        st.success("Settings applied.")

# Initialize pipeline in session state
if "pipeline" not in st.session_state:
    st.session_state.pipeline = RAGPipeline(chunk_size=chunk_size, chunk_overlap=chunk_overlap, top_k=top_k)

# Handle uploaded PDFs
if uploaded_files:
    for uploaded_file in uploaded_files:
        # Save to a temporary location
        save_path = Path("temp_uploads") / uploaded_file.name
        os.makedirs(save_path.parent, exist_ok=True)
        with open(save_path, "wb") as f:
            f.write(uploaded_file.getbuffer())
        try:
            num_chunks = st.session_state.pipeline.add_pdf(str(save_path))
            st.success(f"Processed `{uploaded_file.name}` – {num_chunks} chunks added.")
        except Exception as e:
            st.error(f"Error processing `{uploaded_file.name}`: {e}")

st.divider()

# Chat interface
if "messages" not in st.session_state:
    st.session_state.messages = []

# Display previous messages
for msg in st.session_state.messages:
    if msg["role"] == "assistant":
        st.markdown(f"**Assistant:** {msg['content']}")
        if msg.get("sources"):
            with st.expander("Sources"):
                for src in msg["sources"]:
                    st.markdown(f"- **{src['source']}** (page {src['page']}):\n  > {src['content'][:500]}...")
    else:
        st.markdown(f"**You:** {msg['content']}")

# Input box for new question
question = st.chat_input("Ask a question about the uploaded documents")
if question:
    with st.spinner("Generating answer…"):
        result = st.session_state.pipeline.answer_query(question)
        answer = result["answer"]
        sources = result["sources"]
    st.session_state.messages.append({"role": "user", "content": question})
    st.session_state.messages.append({"role": "assistant", "content": answer, "sources": sources})
    st.markdown(f"**Assistant:** {answer}")
    if sources:
        with st.expander("Sources"):
            for src in sources:
                st.markdown(f"- **{src['source']}** (page {src['page']}):\n  > {src['content'][:500]}...")

# Document summary and clause extraction (simple placeholders)
st.sidebar.header("Analysis Tools")
if st.sidebar.button("Summarize Documents"):
    # Simple summary: concatenate first few chunks
    all_docs = st.session_state.pipeline.documents
    if not all_docs:
        st.sidebar.warning("No documents uploaded.")
    else:
        summary = " ".join([doc.page_content[:200] for doc in all_docs[:5]]) + "..."
        st.sidebar.success("Summary generated.")
        st.sidebar.write(summary)

if st.sidebar.button("Extract Key Clauses"):
    # Very naive keyword search for demonstration
    clauses = {"termination": [], "notice period": [], "payment": [], "confidentiality": [], "obligations": [], "renewal": [], "penalties": []}
    for doc in st.session_state.pipeline.documents:
        content = doc.page_content.lower()
        for keyword in clauses.keys():
            if keyword in content:
                clauses[keyword].append({"source": doc.metadata.get('source'), "page": doc.metadata.get('page'), "snippet": doc.page_content[:200]})
    st.sidebar.subheader("Extracted Clauses")
    for k, v in clauses.items():
        if v:
            st.sidebar.write(f"**{k.title()}**:")
            for item in v:
                st.sidebar.write(f"- {item['source']} (page {item['page']}): {item['snippet']}...")

st.caption("Disclaimer: The responses are generated by an AI model and are for informational purposes only. They do not constitute legal advice.")
